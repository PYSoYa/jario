-- 연신내 좌표 수정.
--
-- 0011에서 연신내가 **중랑구 신내2동**에 찍혔다. 실제 연신내는 은평구 갈현동이고,
-- 15.4km 어긋나 있었다.
--
-- 원인은 상권명을 행정동에 맞출 때 쓴 접미어 규칙이다. '계양계산'을 계산동에
-- 맞추려고 접두어뿐 아니라 접미어도 보게 했는데, 그러자 '연신내'의 접미어 '신내'가
-- 중랑구 **신내동**에 걸렸다. 연신내라는 행정동은 없으므로 더 긴 키가 이기지 못했다.
--
-- 다른 67곳은 지도 API 후보들의 중앙값과 2.5km 이내로 일치한다. 이 한 곳만 틀렸다.
-- 밀도 검사(주변 업소 수)로는 못 잡힌다 — 신내2동도 번화한 동네라 점이 많다.
-- **엉뚱한 자리에 그럴듯하게 찍히는 종류**라, 서로 다른 방법으로 구한 좌표를
-- 대조해야만 드러난다.
--
-- 은평구 갈현동 연신내로데오거리. 반경 300m 업소 1,422곳.

UPDATE market_district
SET lon = 126.919597, lat = 37.618820, coord_source = '이름일치(0012 수정)'
WHERE sido = '서울' AND name = '연신내';

DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM market_district
  WHERE name = '연신내' AND lon BETWEEN 126.91 AND 126.93;
  IF n <> 1 THEN
    RAISE EXCEPTION '연신내 좌표 수정이 적용되지 않았습니다(%건).', n;
  END IF;
END $$;
