-- 상권별 공실률·임대료 (한국부동산원 상업용부동산 임대동향조사, 소규모상가)
--
-- 밀도와 회전율은 "얼마나 많고 얼마나 바뀌는가"를 말한다. 공실률과 임대료는
-- "그래서 자리가 남는가, 얼마나 드는가"를 말한다. 창업 판단에는 둘 다 필요하다.
--
-- ── 좌표가 없는 데이터를 지도에 올리기 ────────────────────────────
-- 원본은 상권을 '서울/도심/광화문' 같은 이름으로만 준다. 상권 구획도가 같이 공개돼
-- 있지만 **JPG 이미지**라 경계를 쓸 수 없다. 점-폴리곤 판정은 불가능하다.
--
-- 그래서 상권마다 대표 좌표를 하나씩 붙였다. 카카오 키워드 검색의 첫 결과를 쓰면
-- 안 된다 — 동명의 랜드마크가 잡힌다. 실제로 68개 중 13개가 그랬다:
--   신촌/이대 → 안산자락길(등산로)   천호 → 광진교      종로 → 경복궁
-- 주변 업소가 0~7곳인 산과 공원이었다.
--
-- 최종 규칙(우리 데이터로 검증한다):
--   1. 상권명이 행정동과 맞으면 그 동에서 **업소가 가장 밀집한 100m 격자** — 43개.
--      중심점(평균 좌표)을 쓰면 안 된다. 행정 구역의 기하학적 중심은 상권 중심이 아니다 —
--      불광역·화곡·상계역이 반경 300m에 130~150곳뿐인 주택가에 찍혔다.
--      시군구까지 묶는다.
--      '신사'는 강남구와 은평구 양쪽에 있어, 묶지 않으면 두 동네의 중간(업소 0곳)이 나온다.
--      접두어뿐 아니라 접미어도 본다 — '계양계산'은 접두어로는 계산동을 못 찾는다.
--   2. 아니면 카카오 후보 중 고른다 — 25개. 후보들의 다수 시군구로 먼저 거르고
--      (그래야 '북촌'이 중구의 '북촌손두부'가 아니라 종로구 북촌문화센터가 된다),
--      주소에 이름이 있는 것을 우선하고, 마지막에 업소 밀도로 정한다.
--   3. 두 상권이 같은 점이 되면(잠실새내역/잠실·송파) 하나를 카카오 쪽으로 되돌린다.
--
-- 검수: 반경 300m 업소 수 최저 119곳(약수역). 처음 규칙에서는 0곳이었다.
--
-- ── 이 수를 "이 자리의 공실률"이라 부르지 않는다 ──────────────────
-- 경계를 모르므로 소속을 판정할 수 없다. 화면에는 "가장 가까운 조사 상권"과
-- **거리를 함께** 적고, 멀면 아예 표시하지 않는다.

CREATE TABLE market_district (
  sido         text NOT NULL,
  name         text NOT NULL,
  lon          double precision NOT NULL,
  lat          double precision NOT NULL,

  vacancy_rate numeric(4,1),   -- %
  rent_per_m2  numeric(6,1),   -- 천원/㎡

  -- 좌표를 어떻게 정했는지. 나중에 의심스러운 값을 되짚을 수 있어야 한다.
  coord_source text NOT NULL,

  geom geography(Point, 4326)
    GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon, lat), 4326)::geography) STORED,

  PRIMARY KEY (sido, name)
);

CREATE INDEX market_district_geom_idx ON market_district USING gist (geom);

COMMENT ON TABLE market_district IS
  '한국부동산원 상업용부동산 임대동향조사(소규모상가) 2026년 2분기 기준. 서울 59 · 인천 9. '
  '좌표는 조사에 없어 우리가 붙인 대표점이다 — 상권 경계가 아니다.';

